#!/usr/bin/env node
// Generates seed/sql/002_seed.sql from the JSON files in seed/data, so the JSON stays the
// single source of truth. Upserts by id, so it is safe to re-run after editing the JSON.
// Run: node scripts/build-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(path.join(root, "seed", "data", f), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
};

function upsert(table, columns, rows, key = "id") {
  if (!rows.length) return "";
  const values = rows.map((r) => `  (${columns.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  const updates = columns.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`).join(", ");
  return `insert into ${table} (${columns.join(", ")}) values\n${values}\non conflict (${key}) do update set ${updates};\n`;
}

const services = read("services.json");
const policies = read("policies.json");
const customers = read("customers.json");
const jobs = read("jobs.json");
const districts = read("service-areas.json").zones.flatMap((z) =>
  Object.entries(z.districts).map(([district, area_name]) => ({
    district,
    zone: z.zone,
    area_name,
    travel_surcharge: z.travel_surcharge,
    response_target_minutes: z.response_target_minutes,
  })),
);

const sql = [
  "-- GENERATED by scripts/build-seed-sql.mjs from seed/data/*.json. Do not edit by hand.",
  "-- Fictional demo data for Harbourline Plumbing & Heating.",
  "begin;",
  upsert("services", ["id", "name", "category", "description", "price_basis", "price_min", "price_max", "price_note", "typical_duration_minutes", "requires_survey", "keywords"], services),
  upsert("policies", ["id", "title", "category", "applies_to", "body"], policies),
  upsert("service_area_districts", ["district", "zone", "area_name", "travel_surcharge", "response_target_minutes"], districts, "district"),
  upsert("customers", ["id", "first_name", "last_name", "company_name", "customer_type", "email", "phone", "address_line1", "town", "postcode", "customer_since", "notes"], customers),
  upsert("jobs", ["id", "customer_id", "service_id", "status", "job_date", "amount", "reference", "engineer", "notes"], jobs),
  "commit;",
  "",
].join("\n");

const out = path.join(root, "seed", "sql", "002_seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${path.relative(root, out)}: ${services.length} services, ${policies.length} policies, ${districts.length} districts, ${customers.length} customers, ${jobs.length} jobs`);
