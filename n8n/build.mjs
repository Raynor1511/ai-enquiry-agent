// ---------------------------------------------------------------------------------------------
// 3. Test intake: protected webhook used by the evaluation script

const testIntake = workflow(
  WF.testIntake,
  [
    {
      name: "Test enquiry webhook", type: "n8n-nodes-base.webhook", typeVersion: 2, position: [0, 0], webhookId: uuid("webhook/test-intake"),
      parameters: { httpMethod: "POST", path: PATHS.testWebhook, authentication: "headerAuth", responseMode: "responseNode", options: {} },
      credentials: cred("httpHeaderAuth", CRED.testWebhook),
    },
    codeNode("Normalise test enquiry", [240, 0], code("normalise", `return { json: fromTestWebhook($json.body) };`)),
    callClassify("Classify (test)", [480, 0]),
    {
      name: "Return result", type: "n8n-nodes-base.respondToWebhook", typeVersion: 1.1, position: [720, 0],
      parameters: { respondWith: "json", responseBody: "={{ JSON.stringify($json) }}", options: {} },
    },
  ],
  [
    ["Test enquiry webhook", "Normalise test enquiry"],
    ["Normalise test enquiry", "Classify (test)"],
    ["Classify (test)", "Return result"],
  ],
);

// ---------------------------------------------------------------------------------------------

export const WORKFLOWS = [
  // n8n 2.x only lets a workflow call published (active) sub-workflows, so Classify is activated first.
  { file: "classify.json", workflow: classify, activate: true },
  { file: "intake.json", workflow: intake, activate: true },
  { file: "test-intake.json", workflow: testIntake, activate: true },
];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(here, "workflows");
  mkdirSync(out, { recursive: true });
  for (const { file, workflow: wf } of WORKFLOWS) {
    writeFileSync(path.join(out, file), JSON.stringify(wf, null, 2) + "\n");
    console.log(`  wrote n8n/workflows/${file}  (${wf.nodes.length} nodes)`);
  }
}
