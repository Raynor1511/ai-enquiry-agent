/** One unrolled turn of the tool loop: Claude call -> handle -> done? -> MCP calls -> collect results. */
function draftTurn(k, x) {
  const prev = k === 1 ? "Start draft" : `Tool results ${k - 1}`;
  return {
    nodes: [
      claudeDraftNode(`Claude: draft turn ${k}`, [x, 500]),
      codeNode(`Turn ${k}`, [x + 220, 500], code("drafting", `
const prev = $(${JSON.stringify(prev)}).first().json;
const r = handleTurn(prev.state, $input.first().json);
if (r.done) return [{ json: { ctx: prev.ctx, state: r.state, done: true, final: r.final ?? null, error: r.error ?? null } }];
return r.toolCalls.map((call, i) => ({ json: { ctx: prev.ctx, state: r.state, done: false, calls: r.toolCalls, body: mcpCallBody(call, i + 1) } }));`), "runOnceForAllItems"),
      ifTrue(`Done ${k}?`, [x + 440, 500], "$json.done"),
      ...(k < MAX_TURNS
        ? [
            mcpNode(`MCP: call tools ${k}`, [x + 660, 680], "={{ JSON.stringify($json.body) }}"),
            codeNode(`Tool results ${k}`, [x + 880, 680], code("drafting", `
const calls = $(${JSON.stringify(`Turn ${k}`)}).first().json;
const state = addToolResults(calls.state, calls.calls, $input.all().map((i) => i.json));
return [{ json: { ctx: calls.ctx, state, request: draftRequest(state, { model: DRAFT_MODEL, systemPrompt: DRAFT_SYSTEM_PROMPT }) } }];`), "runOnceForAllItems"),
          ]
        : []),
    ],
    edges: [
      [`Claude: draft turn ${k}`, `Turn ${k}`],
      [`Turn ${k}`, `Done ${k}?`],
      [`Done ${k}?`, "Finalise draft", 0],
      ...(k < MAX_TURNS
        ? [[`Done ${k}?`, `MCP: call tools ${k}`, 1], [`MCP: call tools ${k}`, `Tool results ${k}`], [`Tool results ${k}`, `Claude: draft turn ${k + 1}`]]
        : []),
    ],
  };
}
