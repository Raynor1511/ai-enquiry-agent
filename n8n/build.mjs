const uuid = (seed) => {
  const h = createHash("sha256").update(seed).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const cred = (type, name) => ({ [type]: { id: `__CREDENTIAL__${name}`, name } });

/**
 * A workflow from nodes and [from, to, output] edges. Every workflow except the Alerts workflow itself
 * names Alerts as its error workflow, so any failed execution posts to #alerts.
 */
function workflow(name, nodes, edges, settings = {}) {
  const names = new Set(nodes.map((n) => n.name));
  if (names.size !== nodes.length) throw new Error(`${name}: duplicate node names`);
  const connections = {};
  for (const [from, to, output = 0] of edges) {
    if (!names.has(from) || !names.has(to)) throw new Error(`${name}: edge ${from} -> ${to} names a missing node`);
    connections[from] ??= { main: [] };
    while (connections[from].main.length <= output) connections[from].main.push([]);
    connections[from].main[output].push({ node: to, type: "main", index: 0 });
  }
  return {
    name,
    nodes: nodes.map((n) => ({ id: uuid(`${name}/${n.name}`), ...n })),
    connections,
    settings: {
      executionOrder: "v1", timezone: "Europe/London", saveDataErrorExecution: "all", saveDataSuccessExecution: "all",
      ...(name === WF.alerts ? {} : { errorWorkflow: `__WORKFLOW__${WF.alerts}` }),
      ...settings,
    },
  };
}

/** Every $("Node") a Code node or expression mentions (to check that each one exists in the workflow). */
export function nodeReferences(wf) {
  const found = [];
  const walk = (v) => {
    if (typeof v === "string") for (const m of v.matchAll(/\$\((["'])((?:(?!\1).)+)\1\)/g)) found.push(m[2]);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  wf.nodes.forEach((n) => walk(n.parameters));
  return [...new Set(found)];
}
function checkReferences(wf) {
  const names = new Set(wf.nodes.map((n) => n.name));
  const missing = nodeReferences(wf).filter((r) => !names.has(r));
  if (missing.length) throw new Error(`${wf.name}: references to missing nodes: ${missing.join(", ")}`);
}

