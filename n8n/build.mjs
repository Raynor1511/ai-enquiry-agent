const uuid = (seed) => {
  const h = createHash("sha256").update(seed).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const cred = (type, name) => ({ [type]: { id: `__CREDENTIAL__${name}`, name } });

function workflow(name, nodes, edges, settings = {}) {
  const connections = {};
  for (const [from, to, output = 0] of edges) {
    connections[from] ??= { main: [] };
    while (connections[from].main.length <= output) connections[from].main.push([]);
    connections[from].main[output].push({ node: to, type: "main", index: 0 });
  }
  return {
    name,
    nodes: nodes.map((n) => ({ id: uuid(`${name}/${n.name}`), ...n })),
    connections,
    settings: { executionOrder: "v1", timezone: "Europe/London", saveDataErrorExecution: "all", saveDataSuccessExecution: "all", ...settings },
  };
}

